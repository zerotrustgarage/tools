// Browser-check a real, generated Scanner HTML report.
// Usage: node uitest/report.mjs <generated-html-path> [screenshots-dir]
// Requires the existing Playwright install and Chromium used by run.mjs.
import { createRequire } from "node:module";
import { readFile, mkdir } from "node:fs/promises";
import { createServer } from "node:http";
import { resolve } from "node:path";
import assert from "node:assert/strict";

const { chromium } = createRequire(import.meta.url)("playwright");
const reportPath = process.argv[2];
assert.ok(reportPath, "usage: node uitest/report.mjs <generated-html-path> [screenshots-dir]");
const shots = process.argv[3] ? resolve(process.argv[3]) : undefined;
if (shots) await mkdir(shots, { recursive: true });
const html = await readFile(resolve(reportPath), "utf8");
assert.ok(html.includes("Content-Security-Policy"), "report must retain its CSP");
// Serve the exact generated bytes locally. Some managed Chromium builds block
// file:// navigation, while localhost preserves the same CSP and resource checks.
const server = createServer((_request, response) => {
  response.writeHead(200, { "content-type": "text/html; charset=utf-8" });
  response.end(html);
}).listen(0, "127.0.0.1");
await new Promise((resolveListen) => server.once("listening", resolveListen));
const reportURL = `http://127.0.0.1:${server.address().port}/report.html`;

const browser = await chromium.launch(process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {});
try {
  const pages = {};
  const resourceRequests = [];
  const pageErrors = [];
  for (const scheme of ["light", "dark"]) {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, colorScheme: scheme });
    page.on("pageerror", (e) => pageErrors.push(`${scheme}: ${e}`));
    page.on("request", (request) => {
      if (request.resourceType() !== "document" || request.url() !== reportURL) resourceRequests.push(`${scheme}: ${request.url()}`);
    });
    await page.goto(reportURL, { waitUntil: "load" });
    pages[scheme] = page;

    const audit = await page.evaluate(() => {
      const text = document.body.innerText;
      const badNodes = [...document.querySelectorAll("script, iframe, object, embed, form, img, link[rel=stylesheet]")].map((e) => e.outerHTML);
      const eventAttrs = [...document.querySelectorAll("*")].flatMap((el) =>
        [...el.attributes].filter((a) => /^on/i.test(a.name)).map((a) => `${el.tagName}[${a.name}]`));
      const anchors = [...document.querySelectorAll("a")].map((a) => a.getAttribute("href"));
      const rootStyle = getComputedStyle(document.documentElement);
      const bodyStyle = getComputedStyle(document.body);
      return {
        text,
        badNodes,
        eventAttrs,
        anchors,
        bg: bodyStyle.backgroundColor,
        fg: bodyStyle.color,
        rootBG: rootStyle.getPropertyValue("--bg").trim(),
        rootText: rootStyle.getPropertyValue("--text").trim(),
        scrollWidth: document.documentElement.scrollWidth,
        clientWidth: document.documentElement.clientWidth,
      };
    });
    assert.deepEqual(audit.badNodes, [], `${scheme}: report must contain no executable or active content`);
    assert.deepEqual(audit.eventAttrs, [], `${scheme}: report must contain no event-handler attributes`);
    assert.ok(audit.anchors.every((href) => href?.startsWith("#")), `${scheme}: links must stay inside the report`);
    assert.ok(audit.text.includes("Example Clinic / Main office"), "client label should render");
    for (const item of ["192.168.50.10", "192.168.50.20", "192.168.50.30", "Example Networks", "Edge Router 200", "EX-ROUTER-2048", "Main office closet", "Telnet is open", "Router at the nurses' station.", "<img src=\"https://scanner-report.invalid/pixel\" onerror=\"window.__pwned=1\">", "Reception printer", "Use the lower paper tray for letterhead.", "00:66:77:88:99:aa", "Observed responsive", "Observed unresponsive"]) {
      assert.ok(audit.text.includes(item), `${scheme}: expected rendered report text ${JSON.stringify(item)}`);
    }
    assert.ok(audit.scrollWidth <= audit.clientWidth, `${scheme}: report page overflows horizontally at 1280px`);
    assert.ok(audit.bg && audit.fg, `${scheme}: report needs readable foreground and background colors`);
    if (scheme === "light") pages.lightAudit = audit;
    else pages.darkAudit = audit;
    await page.setViewportSize({ width: 960, height: 720 });
    const narrow = await page.evaluate(() => ({ scrollWidth: document.documentElement.scrollWidth, clientWidth: document.documentElement.clientWidth }));
    assert.ok(narrow.scrollWidth <= narrow.clientWidth, `${scheme}: report page overflows horizontally at 960px`);
    await page.setViewportSize({ width: 1280, height: 900 });
    if (shots) await page.screenshot({ path: resolve(shots, `report-${scheme}.png`), fullPage: true });
  }

  assert.notEqual(pages.lightAudit.bg, pages.darkAudit.bg, "dark theme should change the report background");
  assert.notEqual(pages.lightAudit.fg, pages.darkAudit.fg, "dark theme should change report text color");

  const printPage = pages.light;
  await printPage.emulateMedia({ media: "print", colorScheme: "dark" });
  const printStyle = await printPage.evaluate(() => ({
    bg: getComputedStyle(document.body).backgroundColor,
    color: getComputedStyle(document.body).color,
    text: document.body.innerText,
  }));
  assert.equal(printStyle.bg, "rgb(255, 255, 255)", "print media should use a white background");
  assert.ok(printStyle.text.includes("192.168.50.10") && printStyle.text.includes("How to read this report"), "print view should retain meaningful report content");
  if (shots) await printPage.pdf({ path: resolve(shots, "report-print.pdf"), printBackground: true });
  assert.deepEqual(pageErrors, [], "generated report must not cause page errors");
  assert.deepEqual(resourceRequests, [], "self-contained report must make no network or subresource requests");
} finally {
  await browser.close();
  server.close();
}
console.log("generated Scanner HTML report passed browser checks");
